class IoUScore(tf.keras.metrics.Metric):
    """
    Computes foreground IoU across one full epoch.

    Args:
        name: str. Name of the metric.
        threshold: float. Probability threshold used to convert predictions into binary masks.
    """
    def __init__(self, name: str = "iou_score", threshold: float = 0.5, **kwargs) -> None:
        super().__init__(name=name, **kwargs)
        self.threshold = threshold
        self.intersection = self.add_weight(name="intersection", initializer="zeros")
        self.union = self.add_weight(name="union", initializer="zeros")

    def update_state(self, y_true: tf.Tensor, y_pred: tf.Tensor, sample_weight=None) -> None:
        """
        Updates intersection and union using one batch of masks and predictions.

        Args:
            y_true: tf.Tensor. True binary masks of shape (batch_size, 128, 128, 1).
            y_pred: tf.Tensor. Predicted probability masks of shape (batch_size, 128, 128, 1).
            sample_weight: Optional sample weights. Not used in this lab.
        """
        # TODO ============================================================================================
        # 1. Convert y_true into a tf.float32 mask
        # 2. Convert y_pred into a tf.float32 mask using self.threshold
        # 3. Compute foreground intersection and union for this batch
        # 4. Add this batch intersection and union to the stored metric state using `assign_add`
        # =================================================================================================
        y_true = tf.cast(y_true > 0.5, tf.float32)
        y_pred = tf.cast(y_pred > self.threshold, tf.float32)
        self.intersection.assign_add(tf.reduce_sum(y_true * y_pred))
        self.union.assign_add(tf.reduce_sum(tf.cast((y_true + y_pred) >= 1, tf.float32)))

        

    def result(self) -> tf.Tensor:
        """
        Computes IoU from the accumulated intersection and union.

        Returns:
            iou: tf.Tensor. Foreground IoU score.
        """
        # TODO ====================================================================
        # 1. Retrieve accumulated intersection and union
        # 2. Return intersection / union (add 1e-8 to avoid division by zero)
        # =========================================================================
        return self.intersection / (self.union + 1e-8)

    def reset_state(self) -> None:
        """
        Clears the stored intersection and union before Keras starts a new epoch or evaluation.
        """
        self.intersection.assign(0.0)
        self.union.assign(0.0)

