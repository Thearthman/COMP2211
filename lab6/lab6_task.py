"""## Task 3: Customized F1 Metric Implementation

In this task, you will convert F1-Score into a TensorFlow standard evaluation metric to record model performance while training. Be careful: your custom F1 metric should be **stateful across the full epoch**, rather than computing F1 independently for each batch.


---
**How Keras metric overriding works**

`MacroF1Score(tf.keras.metrics.Metric)` creates a custom metric by inheriting from the base `tf.keras.metrics.Metric` class. Keras expects a metric object to keep its own state and update that state batch by batch:
- `__init__(...)` creates persistent state variables, such as `self.cm`.
- `update_state(...)` is called once for each batch and should update the stored state.
- `result(...)` converts the stored state into the number Keras reports.
- `reset_state(...)` clears the stored state before a new epoch or evaluation run.

These methods are called by Keras automatically during `fit(...)` and `evaluate(...)`. Implementing them correctly is important because a broken metric can make training progress look misleading even when the model code runs without errors.

---

> Why Macro F1?  
> Accuracy tells us how many predictions are correct overall, but it does not always show whether the model performs well on every class. In speech recognition, some commands may be easier than others. A **Macro F1 Score** computes F1 for each class separately and then averages them, so every class contributes equally.

### Task 3.1: Updating the Metric State
Keras will call `update_state(...)` once for each batch during training and validation. In this function, your job is to update `self.cm`, the confusion matrix stored inside the metric object.

### Task 3.2: Computing the Metric Result
Keras will call `result(...)` when it needs the current Macro F1 value. In this function, your job is to compute Macro F1 from the accumulated confusion matrix `self.cm`.

---
**Suggested TensorFlow Components**
- `tf.keras.metrics.Metric` : https://www.tensorflow.org/api_docs/python/tf/keras/metrics/Metric
- `tf.argmax` : https://www.tensorflow.org/api_docs/python/tf/math/argmax
- `tf.math.confusion_matrix` : https://www.tensorflow.org/api_docs/python/tf/math/confusion_matrix
- `tf.linalg.diag_part` : https://www.tensorflow.org/api_docs/python/tf/linalg/diag_part
- `tf.reduce_sum` : https://www.tensorflow.org/api_docs/python/tf/math/reduce_sum
- `tf.reduce_mean` : https://www.tensorflow.org/api_docs/python/tf/math/reduce_mean
- `tf.zeros` : https://www.tensorflow.org/api_docs/python/tf/zeros
- `assign_add` : https://www.tensorflow.org/api_docs/python/tf/Variable#assign_add

"""

class MacroF1Score(tf.keras.metrics.Metric):
    """
    Computes macro F1 score across one full epoch.

    Args:
        num_classes: int. Number of classes in the classification task.
        name: str. Name of the metric.
    """
    def __init__(self, num_classes: int, name: str = "f1_score", **kwargs):
        super().__init__(name=name, **kwargs)
        self.num_classes = num_classes
        self.cm = self.add_weight(
            name="confusion_matrix",
            shape=(num_classes, num_classes),
            initializer="zeros",
        )

    def update_state(self, y_true: tf.Tensor, y_pred: tf.Tensor, sample_weight=None) -> None:
        """
        Updates the confusion matrix using one batch of labels and predictions.

        Args:
            y_true: tf.Tensor. True labels of shape (batch_size,).
            y_pred: tf.Tensor. Predicted probabilities of shape (batch_size, num_classes).
            sample_weight: Optional sample weights. Not used in this lab.
        """
        # TODO ============================================================================================
        # 1. Convert predicted probabilities to predicted class labels
        # 2. Build the confusion matrix for this batch using `tf.math.confusion_matrix`
        # 3. Add this batch confusion matrix to the stored epoch confusion matrix using `assign_add`
        # NOTE: Data type of your batch confusion matrix should be tf.float32
        # =================================================================================================
        y_pred_class = tf.math.argmax(y_pred,axis=1)
        batch_cm = tf.math.confusion_matrix(y_true,y_pred_class,num_classes=self.num_classes,weights=sample_weight)
        self.cm.assign_add(batch_cm)

    def result(self) -> tf.Tensor:
        """
        Computes macro F1 score from the accumulated confusion matrix.

        Returns:
            macro_f1: tf.Tensor. Mean F1 score over all classes.
        """
        # TODO ====================================================================
        # 1. Extract true positives from the diagonal of the confusion matrix
        # 2. Compute false positives and false negatives for each class
        # 3. Compute precision and recall for each class (add 1e-8 to avoid division by zero)
        # 4. Compute F1 score for each class (add 1e-8 to avoid division by zero)
        # 5. Return the average F1 score across all classes
        # NOTE: Retrieve values from `self.cm`
        # =========================================================================
        TP = tf.linalg.diag_part(self.cm)
        FP_TP = tf.reduce_sum(self.cm,axis=0) + 1e-8
        FN_TP = tf.reduce_sum(self.cm,axis=1) + 1e-8
        precision = TP / FP_TP
        recall = TP/ FN_TP
        f1 = 2 * precision * recall / (precision + recall + 1e-8)
        macro_f1 = tf.reduce_mean(f1)

        return macro_f1

    def reset_state(self) -> None:
        """
        Clears the stored confusion matrix before Keras starts a new epoch or evaluation.
        """
        self.cm.assign(tf.zeros((self.num_classes, self.num_classes), dtype=tf.float32))

